#!/usr/bin/env python3
"""Inline the About CSS into index.html so first paint needs no CSS request (DESIGN.md §5, like events/build.sh).
Downloadable @font-face rules go to assets/fonts.css instead; the page loads that on the first interaction.

Edit the readable sources (assets/about.css, assets/site.css), then run:

    python3 build.py

shortcut: regex minifier (comments/whitespace only); swap for esbuild/lightningcss if sources grow.
"""
import re
from pathlib import Path

ROOT = Path(__file__).parent
SOURCES = ["assets/about.css", "assets/site.css"]  # same order as the old <link> tags
PAGES = ["index.html", "history.html"]  # contact.html still links its CSS (it also needs pico + contact.css)
# the page's run of about/site/contact <link>s (first build) or the bundle a previous build inlined
TAG = re.compile(
    r'<link rel="stylesheet" href="assets/(?:about|site|contact)\.css[^"]*">(?:\s*<link rel="stylesheet" href="assets/(?:about|site|contact)\.css[^"]*">)*'
    r'|<style data-bundle>.*?</style>',
    re.S,
)


def min_css(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r"\s*([{};,])\s*", r"\1", s)  # never touch spaces before ':' (descendant selectors like ".x :hover")
    s = re.sub(r":\s+", ":", s)
    return s.replace(";}", "}").strip()


def rebase(css):
    # url()s were relative to assets/; inlined, they resolve against the page
    return re.sub(r'url\("(?!data:|/|https?:|#)', 'url("assets/', css)


FONT_FACE = re.compile(r"@font-face\{[^}]*\}")


def split_fonts(css):
    """Faces that download a file -> fonts.css (deduped, order kept); local() fallback faces stay inline."""
    remote = [f for f in FONT_FACE.findall(css) if "url(" in f]
    return FONT_FACE.sub(lambda m: "" if "url(" in m.group() else m.group(), css), "".join(dict.fromkeys(remote))


def main():
    src = "".join((ROOT / f).read_text() for f in SOURCES)
    page_css, font_css = split_fonts(min_css(src))
    css = rebase(page_css)

    # self-checks: braces survive, data URIs untouched, nothing can close the <style> early
    bare = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    faces = len(FONT_FACE.findall(min_css(src))) - len(FONT_FACE.findall(css))  # moved out, incl. duplicates
    assert css.count("{") + faces == bare.count("{") and css.count("}") + faces == bare.count("}"), "CSS brace mismatch"
    assert "url(" in font_css and "url(" not in "".join(FONT_FACE.findall(css)), "font faces not split"
    assert re.findall(r'url\("data:[^"]*"\)', css) == re.findall(r'url\("data:[^"]*"\)', bare), "data URI changed"
    assert "</style" not in css.lower(), "bundle contains </style>"

    (ROOT / "assets/fonts.css").write_text("/* generated by build.py from @font-face in about.css + site.css */\n" + font_css + "\n")
    for page in PAGES:
        p = ROOT / page
        html = p.read_text()
        assert TAG.search(html), f"{page}: no CSS tags to replace"
        p.write_text(TAG.sub(lambda _: f"<style data-bundle>{css}</style>", html, count=1))
    print(f"inlined {len(css)} B of CSS into {', '.join(PAGES)}; fonts.css {len(font_css)} B")


if __name__ == "__main__":
    main()
